// Byte-exact draft-22 vectors, shared with the Rust codec.
//
// Every vector lives in `Tests/Fixtures/moqt-22/<name>.hex`, in a format meant
// to be read by something other than this file:
//
//   - lines beginning `#` are comments, and say what the bytes are;
//   - everything else is hex, two digits per byte, with whitespace ignored;
//   - the file name, without `.hex`, is the vector's name.
//
// Control messages are framed (Type, Length, body), so a reader checks its
// framing too. Message Parameters are a whole parameter block holding one
// parameter (Number of Parameters = 1, Type Delta, value), because a lone
// parameter's value cannot be found without its type. Data-plane vectors are
// the bytes of one stream or datagram.
//
// Each vector here is checked in both directions: the value encodes to the
// file's bytes, and the file's bytes decode to the value. To regenerate after
// a deliberate change, run with `MOQOM_WRITE_FIXTURES=1` and read the diff.
//
// Generated bytes only prove this codec agrees with itself, so the suite also
// pins a handful with hand-written literals worked from the draft's figures —
// those are the tests that would catch a codec and its fixtures drifting
// together.

import Foundation
import MoqomCore
