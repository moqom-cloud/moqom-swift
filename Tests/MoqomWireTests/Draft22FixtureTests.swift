private let draft = MoqtDraft.draft22

private let fixtures = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent()
    .deletingLastPathComponent()
    .appendingPathComponent("Fixtures/moqt-22")

private func framed(_ message: some DraftControlMessage) -> Data {
    var writer = draft.writer()
    try! ControlFrame.write(message, to: &writer)
    return writer.bytes
}

private func framed(_ message: some ControlMessage, as code: Draft22.MessageCode) -> Data {
    var writer = draft.writer()
    try! ControlFrame.write(message, as: code.rawValue, to: &writer)
    return writer.bytes
}

private func block(_ parameter: MessageParameter) -> Data {
    var writer = draft.writer()
    MessageParameters([parameter]).write(to: &writer)
    return writer.bytes
}

/// Undo `framed`, checking the type code.
private func unframe(_ data: Data, _ code: Draft22.MessageCode) throws -> Data {
    var reader = draft.reader(data)
    let frame = try ControlFrame.readRaw(from: &reader)
    #expect(reader.isEmpty)
    #expect(try Draft22.MessageCode(code: frame.code) == code)
    return frame.body
}

private struct Vector: Sendable, CustomTestStringConvertible {
    let name: String
    let note: String
    let bytes: Data
    /// Decode the fixture's bytes and compare with the value they came from.
    let check: @Sendable (Data) throws -> Void

    var testDescription: String { name }
}

private func message<M: DraftControlMessage>(_ name: String, _ note: String, _ value: M) -> Vector {
    let code = try! Draft22.MessageCode(code: M.typeCode)
    return Vector(name: name, note: note, bytes: framed(value)) { data throws in
        #expect(try M.decode(try unframe(data, code), draft) == value)
    }
}

private func shared<M: ControlMessage>(
    _ name: String,
    _ note: String,
    _ value: M,
    _ code: Draft22.MessageCode
) -> Vector {
    Vector(name: name, note: note, bytes: framed(value, as: code)) { data throws in
        #expect(try M.decode(try unframe(data, code), draft) == value)
    }
}

private func parameter(_ name: String, _ note: String, _ value: MessageParameter) -> Vector {
    Vector(name: "param-" + name, note: note, bytes: block(value)) { data throws in
        var reader = draft.reader(data)
        #expect(try MessageParameters.read(from: &reader) == MessageParameters([value]))
        #expect(reader.isEmpty)
    }
}

