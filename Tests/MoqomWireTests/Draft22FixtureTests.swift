private func read(_ name: String) throws -> Data {
    let text = try String(contentsOf: fixtures.appendingPathComponent(name + ".hex"), encoding: .utf8)
    let hex = text.split(separator: "\n").filter { !$0.hasPrefix("#") }.joined()
    return hexBytes(String(hex))
}

private func render(_ vector: Vector) -> String {
    var lines = ["# \(vector.note)"]
    let hex = vector.bytes.map { String(format: "%02x", $0) }
    stride(from: 0, to: hex.count, by: 16).forEach { start in
        lines.append(hex[start ..< min(start + 16, hex.count)].joined(separator: " "))
    }
    return lines.joined(separator: "\n") + "\n"
}

@Suite("Draft-22 fixtures")
struct Draft22FixtureTests {
    @Test("each vector matches its fixture both ways", arguments: vectors)
    fileprivate func vector(_ vector: Vector) throws {
        if ProcessInfo.processInfo.environment["MOQOM_WRITE_FIXTURES"] != nil {
            try FileManager.default.createDirectory(at: fixtures, withIntermediateDirectories: true)
            try render(vector).write(
                to: fixtures.appendingPathComponent(vector.name + ".hex"),
                atomically: true,
                encoding: .utf8
            )
        }
        let stored = try read(vector.name)
        #expect(stored == vector.bytes, "\(vector.name) encodes differently from its fixture")
        try vector.check(stored)
    }

    @Test("no fixture without a vector")
    func noStrays() throws {
        let names = try FileManager.default.contentsOfDirectory(atPath: fixtures.path)
            .filter { $0.hasSuffix(".hex") }
            .map { String($0.dropLast(4)) }
        #expect(Set(names) == Set(vectors.map(\.name)))
    }
}

@Suite("Draft-22 bytes worked by hand")
struct Draft22HandVectorTests {
    /// §8.6's own example, 3-5 and 10-15 as 3, 2, 5, 5, behind SetID 0, a
    /// Length of 5, type 0x26, and a count of one.
    @Test("OBJECTID_FILTER matches §8.6")
    func rangeExample() {
        #expect(block(.objectIDFilter(RangeFilter(ranges: [.init(3, 5), .init(10, 15)])))
            == hexBytes("01 26 05 00 03 02 05 05"))
    }

    /// No length prefix: the filter type says how many varints follow.
    @Test("LOCATION_FILTER has no length")
    func locationFilter() {
        #expect(block(.locationFilter(.absoluteRange(start: Location(group: 3, object: 1), end: Location(group: 5, object: 7))))
            == hexBytes("01 21 04 03 01 02 07"))
        #expect(block(.locationFilter(.nextObject)) == hexBytes("01 21 05"))
    }

    /// uint8, not a varint: 255 is one byte here and would be two in vi64.
    @Test("uint8 parameters are one raw byte")
    func uint8() {
        #expect(block(.subscriberPriority(255)) == hexBytes("01 20 ff"))
        #expect(block(.groupOrder(.descending)) == hexBytes("01 22 02"))
    }

    /// Types are deltas: 0x02, 0x10, 0x20, 0x21, 0x23 go out as 2, 14, 16, 1,
    /// 2. FILL_PARAMETERS' value is itself a counted block, here holding one
    /// LOCATION_FILTER.
    @Test("SUBSCRIBE, field by field")
    func subscribe() {
        let bytes = framed(Draft22.Subscribe(requestID: 0, track: track, parameters: [
            .objectDeliveryTimeout(200),
            .forward(true),
            .subscriberPriority(128),
            .locationFilter(.nextObject),
            .fillParameters([.locationFilter(.relativeStart(groups: 1))]),
        ]))
        let body = hexBytes(
            """
            00
            02 05 6d6f716f6d 04 61636d65
            05 766964656f
            05
            02 80c8
            0e 01
            10 80
            01 05
            02 04 01 21 01 01
            """
        )
        #expect(bytes == hexBytes("03") + hexBytes(String(format: "%04x", body.count)) + body)
    }

    /// End Location is inclusive in draft-22 and goes out as given; draft-19
    /// would have written {12, 5}.
    @Test("FETCH_OK's end is inclusive")
    func fetchOk() {
        #expect(framed(Draft22.FetchOk(end: Location(group: 12, object: 4))) == hexBytes("18 0004 00 0c 04 00"))
    }
}

@Suite("Draft-22 strictness")
struct Draft22StrictnessTests {
    private func parse(_ hex: String) throws -> MessageParameters {
        var reader = draft.reader(hexBytes(hex))
        return try MessageParameters.read(from: &reader)
    }

    @Test("an unknown Message Parameter is a violation, not skipped")
    func unknownParameter() {
        // 0x4D51 is MOQOM's private proof in the draft-19 profile.
        var writer = draft.writer()
        writer.varInt(1)
        writer.varInt(0x4D51)
        writer.varInt(0)
        #expect(throws: WireError.self) {
            var reader = draft.reader(writer.bytes)
            _ = try MessageParameters.read(from: &reader)
        }
        #expect(throws: WireError.self) { try parse("01 07 00") }
    }

    @Test("a parameter the message does not allow is a violation")
    func notAllowed() {
        // EXPIRES in a SUBSCRIBE.
        let body = draft.writer()
        var writer = body
        writer.varInt(0)
        track.write(to: &writer)
        MessageParameters([.expires(5)]).write(to: &writer)
        #expect(throws: WireError.self) { try Draft22.Subscribe.decode(writer.bytes, draft) }
    }

    @Test("a repeat of a non-repeating parameter is a violation")
    func repeated() throws {
        let twice = try parse("02 20 01 00 02")
        #expect(throws: WireError.self) { try twice.validate(allowing: [.subscriberPriority], in: "SUBSCRIBE") }
        // Tokens may repeat.
        let tokens = MessageParameters([
            .authorizationToken(.useAlias(1)),
            .authorizationToken(.useAlias(2)),
        ])
        try tokens.validate(allowing: [.authorizationToken], in: "PUBLISH_NAMESPACE")
    }

    @Test("FILL_PARAMETERS may only carry Table 7")
    func fillContents() {
        // FILL_PARAMETERS holding FORWARD.
        #expect(throws: WireError.self) { try parse("01 23 03 01 10 01") }
    }

    @Test("uint8 booleans and orders are range-checked")
    func ranges() {
        #expect(throws: WireError.self) { try parse("01 10 02") }
        #expect(throws: WireError.self) { try parse("01 35 07") }
        #expect(throws: WireError.self) { try parse("01 22 03") }
        #expect(throws: WireError.self) { try parse("01 21 06") }
    }

    @Test("trailing bytes after a body are a violation")
    func trailing() {
        #expect(throws: WireError.self) { try Draft22.RequestOk.decode(hexBytes("00 00"), draft) }
        #expect(throws: WireError.self) { try Draft22.FetchOk.decode(hexBytes("00 0c"), draft) }
    }

    @Test("retired message codes are named as such")
    func reserved() {
        for code: UInt64 in [0x20, 0x21, 0x1E, 0x40] {
            #expect(throws: WireError.self) { try Draft22.MessageCode(code: code) }
        }
        #expect(throws: WireError.self) { try Draft22.MessageCode(code: 0x99) }
        #expect(try! Draft22.MessageCode(code: 0x22) == .publishStateNotify)
    }
}
