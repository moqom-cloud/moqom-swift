// Identity: a username, a device key, and nothing in between.
//
// The whole point of this file is what it does *not* contain. There is no
// numeric UID, no mapping table, and no place to add one. Agora's integer UIDs
// force every application that has string usernames to maintain a bidirectional
// map, and that map is a permanent source of drift, a lookup on the join path,
// and a hard constraint that leaks into features that have nothing to do with
// media — their cross-channel relay forbids string UIDs outright.
//
// MOQT lets us avoid it entirely: the username is the token's `sub` claim
// verbatim and a field in the namespace tuple. Multi-device works because the
// device is its *own* tuple field rather than a suffix glued onto the username,
// which removes separator collisions, ambiguous parsing when a username
// contains the delimiter, and the inability to scope authorisation to just the
// user portion.

import Foundation

/// A user, identified by the string their account is named with.
///
/// This is the `sub` claim of the device's token, unmodified. It is stable
/// across a user's devices and is the only user identifier in the SDK.
public struct Username: Hashable, Sendable, Codable {
    /// The canonicalised username.
    public let value: String

    /// - Throws: ``NameError`` if the username cannot be a namespace field —
    ///   empty, or long enough to overflow a name on its own.
    public init(_ value: String) throws(NameError) {
        let normalised = value.precomposedStringWithCanonicalMapping
        guard !normalised.isEmpty else { throw NameError.emptyField }
        guard normalised.utf8.count <= maximumNameLength else { throw NameError.tooLong }
        self.value = normalised
    }
}

extension Username: CustomStringConvertible {
    public var description: String { value }
}

/// One installation of the app, identified by the key it holds.
///
/// The value is derived from the JWK Thumbprint (`jkt`) of a non-exportable
/// P-256 key generated in the Secure Enclave at install, which is also what the
/// token's `cnf` claim binds to. Deriving the namespace field from the
/// thumbprint rather than from a random string is what makes a device ban and a
/// credential revocation the same act: there is exactly one thing to revoke and
/// it cannot be regenerated by reinstalling with a new random ID.
public struct DeviceID: Hashable, Sendable, Codable {
    /// The namespace-safe rendering of the thumbprint.
    public let value: String

    /// Construct from an already-rendered thumbprint field.
    ///
    /// - Throws: ``NameError`` if it cannot be a namespace field.
    public init(_ value: String) throws(NameError) {
        guard !value.isEmpty else { throw NameError.emptyField }
        guard value.utf8.count <= maximumNameLength else { throw NameError.tooLong }
        self.value = value
    }

    /// Derive the namespace field from a raw JWK thumbprint.
    ///
    /// Truncated to `prefixLength` base64url characters. A full SHA-256
    /// thumbprint is 43 characters and appears in every namespace on the wire,
    /// in every log line, and in every debugging session; the collision
    /// probability across one tenant's devices at 16 characters is negligible
    /// and the token's `cnf` claim carries the untruncated value, so the
    /// authorisation decision never depends on this string being unique.
    public init(thumbprint: String, prefixLength: Int = 16) throws(NameError) {
        try self.init(String(thumbprint.prefix(prefixLength)))
    }
}

extension DeviceID: CustomStringConvertible {
    public var description: String { value }
}

/// A user on a specific device: the thing that actually occupies a namespace.
///
/// One `Username` may be present in a room several times over, once per device.
/// That is a supported state rather than an error to deduplicate — a host on a
/// phone and an iPad is publishing two genuinely different camera feeds.
public struct ParticipantIdentity: Hashable, Sendable, Codable {
    /// The user.
    public let username: Username

    /// Which of their devices this is.
    public let device: DeviceID

    public init(username: Username, device: DeviceID) {
        self.username = username
        self.device = device
    }
}

extension ParticipantIdentity: CustomStringConvertible {
    public var description: String { "\(username)@\(device)" }
}

/// A customer of the platform. The first field of every namespace.
public struct TenantID: Hashable, Sendable, Codable, ExpressibleByStringLiteral {
    public let value: String

    public init(stringLiteral value: String) { self.value = value }
    public init(_ value: String) { self.value = value }
}

extension TenantID: CustomStringConvertible {
    public var description: String { value }
}

/// A room, which exists because there is a row in the control plane's database
/// and not because anyone is currently connected to it.
public struct RoomID: Hashable, Sendable, Codable, ExpressibleByStringLiteral {
    public let value: String

    public init(stringLiteral value: String) { self.value = value }
    public init(_ value: String) { self.value = value }
}

extension RoomID: CustomStringConvertible {
    public var description: String { value }
}

/// The namespace tuples MOQOM builds, in one place.
///
/// Constructing these by hand at call sites is how the field order drifts, and
/// field order is load-bearing: authorisation scopes and roster derivation both
/// match on prefixes, so a namespace with the device before the participant is
/// not a cosmetic difference but a different security boundary.
public enum MoqomNamespaces {
    /// A user's own channel, independent of any room.
    ///
    /// `(tenant, "u", username, device)`
    public static func personal(
        tenant: TenantID,
        identity: ParticipantIdentity
    ) throws(NameError) -> TrackNamespace {
        try personalPrefix(tenant: tenant, username: identity.username)
            .appending(identity.device.value)
    }

    /// The prefix a viewer subscribes to in order to receive every device
    /// that user is live on.
    ///
    /// `(tenant, "u", username)`
    public static func personalPrefix(
        tenant: TenantID,
        username: Username
    ) throws(NameError) -> TrackNamespace {
        try TrackNamespace([tenant.value, "u", username.value])
    }

    /// The prefix a viewer subscribes to in order to receive every participant
    /// on stage, including ones who join later.
    ///
    /// `(tenant, "r", room)`
    public static func room(
        tenant: TenantID,
        room: RoomID
    ) throws(NameError) -> TrackNamespace {
        try TrackNamespace([tenant.value, "r", room.value])
    }

    /// One participant's slot on stage.
    ///
    /// `(tenant, "r", room, username, device)`
    public static func participant(
        tenant: TenantID,
        room: RoomID,
        identity: ParticipantIdentity
    ) throws(NameError) -> TrackNamespace {
        try TrackNamespace([
            tenant.value, "r", room.value, identity.username.value, identity.device.value,
        ])
    }

    /// The prefix for backstage, which deliberately sits *outside* the room
    /// prefix so that a viewer's `SUBSCRIBE_NAMESPACE` cannot reach it.
    ///
    /// `(tenant, "bs", room)`
    public static func backstage(
        tenant: TenantID,
        room: RoomID
    ) throws(NameError) -> TrackNamespace {
        try TrackNamespace([tenant.value, "bs", room.value])
    }

    /// One participant's slot backstage.
    ///
    /// Going live is a change of namespace from this to
    /// ``participant(tenant:room:identity:)`` — no renegotiation, no
    /// reconnection, and no cost proportional to audience size.
    ///
    /// `(tenant, "bs", room, username, device)`
    public static func backstageParticipant(
        tenant: TenantID,
        room: RoomID,
        identity: ParticipantIdentity
    ) throws(NameError) -> TrackNamespace {
        try TrackNamespace([
            tenant.value, "bs", room.value, identity.username.value, identity.device.value,
        ])
    }

    /// Recover the identity from a namespace announced under `prefix`.
    ///
    /// Returns `nil` when the announcement is not under the prefix or does not
    /// have exactly the two trailing fields a participant slot has. That second
    /// check is what stops a deeper namespace — a sub-track, or something a
    /// future draft adds — from being read as a participant and appearing in a
    /// roster it does not belong in.
    public static func identity(
        announcedAt namespace: TrackNamespace,
        under prefix: TrackNamespace
    ) -> ParticipantIdentity? {
        guard let tail = namespace.suffix(after: prefix) else { return nil }
        if tail.count == 2,
           let username = try? Username(tail[0]),
           let device = try? DeviceID(tail[1])
        {
            return ParticipantIdentity(username: username, device: device)
        }
        // A personal channel is announced under `(tenant, "u", username)`, so
        // the suffix is only the device. The username is already in the prefix.
        if tail.count == 1,
           prefix.fields.count >= 3,
           prefix.fields[1] == "u",
           let username = try? Username(prefix.fields[2]),
           let device = try? DeviceID(tail[0])
        {
            return ParticipantIdentity(username: username, device: device)
        }
        return nil
    }
}
